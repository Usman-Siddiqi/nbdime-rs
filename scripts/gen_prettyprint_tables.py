#!/usr/bin/env python3
"""Generates crates/nbdime-core/src/prettyprint/py_tables.rs from the reference Python.

Run with the oracle interpreter (Python 3.13, Unicode 15.1, Pygments installed):

    /home/claude/ref/venv/bin/python scripts/gen_prettyprint_tables.py

The tables are what `repr(str)`, `re`'s `\\s` and `\\w`, and Pygments' `get_lexer_by_name` use.
"""

import re
import sys
import unicodedata
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "crates/nbdime-core/src/prettyprint/py_tables.rs"
SURROGATES = range(0xD800, 0xE000)


def ranges(predicate):
    """Inclusive ranges of the code points (surrogates excluded) that satisfy `predicate`."""
    out = []
    start = None
    for cp in range(0x110000):
        hit = cp not in SURROGATES and predicate(cp)
        if hit and start is None:
            start = cp
        elif not hit and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def emit(name, doc, table):
    lines = [f"/// {doc}", "#[rustfmt::skip]", f"pub const {name}: [u32; {2 * len(table)}] = ["]
    row = []
    for lo, hi in table:
        row.append(f"0x{lo:X}, 0x{hi:X},")
        if len(row) == 6:
            lines.append("    " + " ".join(row))
            row = []
    if row:
        lines.append("    " + " ".join(row))
    lines.append("];")
    return "\n".join(lines)


def main():
    if unicodedata.unidata_version != "15.1.0":
        sys.exit(f"expected Unicode 15.1.0, got {unicodedata.unidata_version}")
    word = re.compile(r"\w")
    from pygments.lexers import LEXERS

    aliases = sorted({a for entry in LEXERS.values() for a in entry[2]})
    parts = [
        "// @generated by scripts/gen_prettyprint_tables.py (Python "
        f"{sys.version.split()[0]}, Unicode {unicodedata.unidata_version}). Do not edit.",
        "//! Character tables of the reference Python and Pygments.",
        "",
        "// Each range table is a flat list of inclusive `start, end` pairs in ascending order.",
        "",
        emit("NON_PRINTABLE", "Code points for which `str.isprintable()` is false.",
             ranges(lambda cp: not chr(cp).isprintable())),
        "",
        emit("SPACE", "Code points that `re`'s `\\s` (and `str.isspace()`) match.",
             ranges(lambda cp: chr(cp).isspace())),
        "",
        emit("WORD", "Code points that `re`'s `\\w` matches in a `str` pattern.",
             ranges(lambda cp: word.match(chr(cp)) is not None)),
        "",
        "/// Aliases of the lexers that `pygments.lexers.get_lexer_by_name` knows, sorted.",
        "#[rustfmt::skip]",
        f"pub const LEXER_ALIASES: [&str; {len(aliases)}] = [",
    ]
    row = []
    for a in aliases:
        row.append(f'"{a}",')
        if len(", ".join(row)) > 80:
            parts.append("    " + " ".join(row))
            row = []
    if row:
        parts.append("    " + " ".join(row))
    parts.append("];")
    OUT.write_text("\n".join(parts) + "\n")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
